const mongoose = require('mongoose');

const collectionCentreSchema = new mongoose.Schema({
  centreName: {
    type: String,
    required: true,
  },
  address: {
    type: String,
    required: true,
  },
  city: {
    type: String,
    required: true,
  },
  phone: {
    type: String,
    required: true,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
});

module.exports = mongoose.model('CollectionCentre', collectionCentreSchema);
